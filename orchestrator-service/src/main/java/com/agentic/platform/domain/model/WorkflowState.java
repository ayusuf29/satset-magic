package com.agentic.platform.domain.model;

public enum WorkflowState {
    PHASE_0_REQUIREMENT_DISCOVERY,
    PHASE_0_WAITING_HUMAN_SIGN_OFF,
    PHASE_1_ARCHITECTURE_AND_DESIGN,
    PHASE_1_WAITING_HUMAN_APPROVAL,
    PHASE_2_BACKLOG_GENERATION,
    PHASE_2_WAITING_HUMAN_APPROVAL,
    PHASE_3_TASK_DISPATCHING,
    PHASE_3_WAITING_HUMAN_APPROVAL,
    PHASE_4_TDD_PLANNING,
    PHASE_4_WAITING_HUMAN_APPROVAL,
    PHASE_5_DEVELOPMENT_IMPLEMENTATION,
    PHASE_5_WAITING_HUMAN_APPROVAL,
    PHASE_6_CODE_REVIEW,
    PHASE_6_WAITING_HUMAN_CODE_REVIEW_AND_MERGE,
    PHASE_6_DEADLOCK_WAITING_HUMAN,
    PHASE_7_QA_VERIFICATION,
    PHASE_7_WAITING_HUMAN_APPROVAL,
    PHASE_8_READY_FOR_PRODUCTION_GATE,
    PHASE_9_RELEASED,
    FAILED;

    public boolean isHumanGate() {
        return this == PHASE_0_WAITING_HUMAN_SIGN_OFF ||
               this == PHASE_1_WAITING_HUMAN_APPROVAL ||
               this == PHASE_2_WAITING_HUMAN_APPROVAL ||
               this == PHASE_3_WAITING_HUMAN_APPROVAL ||
               this == PHASE_4_WAITING_HUMAN_APPROVAL ||
               this == PHASE_5_WAITING_HUMAN_APPROVAL ||
               this == PHASE_6_WAITING_HUMAN_CODE_REVIEW_AND_MERGE ||
               this == PHASE_6_DEADLOCK_WAITING_HUMAN ||
               this == PHASE_7_WAITING_HUMAN_APPROVAL ||
               this == PHASE_8_READY_FOR_PRODUCTION_GATE;
    }

    public WorkflowState getNextDefaultState() {
        return switch (this) {
            case PHASE_0_REQUIREMENT_DISCOVERY -> PHASE_0_WAITING_HUMAN_SIGN_OFF;
            case PHASE_0_WAITING_HUMAN_SIGN_OFF -> PHASE_1_ARCHITECTURE_AND_DESIGN;
            case PHASE_1_ARCHITECTURE_AND_DESIGN -> PHASE_1_WAITING_HUMAN_APPROVAL;
            case PHASE_1_WAITING_HUMAN_APPROVAL -> PHASE_2_BACKLOG_GENERATION;
            case PHASE_2_BACKLOG_GENERATION -> PHASE_2_WAITING_HUMAN_APPROVAL;
            case PHASE_2_WAITING_HUMAN_APPROVAL -> PHASE_3_TASK_DISPATCHING;
            case PHASE_3_TASK_DISPATCHING -> PHASE_3_WAITING_HUMAN_APPROVAL;
            case PHASE_3_WAITING_HUMAN_APPROVAL -> PHASE_4_TDD_PLANNING;
            case PHASE_4_TDD_PLANNING -> PHASE_4_WAITING_HUMAN_APPROVAL;
            case PHASE_4_WAITING_HUMAN_APPROVAL -> PHASE_5_DEVELOPMENT_IMPLEMENTATION;
            case PHASE_5_DEVELOPMENT_IMPLEMENTATION -> PHASE_5_WAITING_HUMAN_APPROVAL;
            case PHASE_5_WAITING_HUMAN_APPROVAL -> PHASE_6_CODE_REVIEW;
            case PHASE_6_CODE_REVIEW -> PHASE_6_WAITING_HUMAN_CODE_REVIEW_AND_MERGE;
            case PHASE_6_WAITING_HUMAN_CODE_REVIEW_AND_MERGE -> PHASE_7_QA_VERIFICATION;
            case PHASE_6_DEADLOCK_WAITING_HUMAN -> PHASE_5_DEVELOPMENT_IMPLEMENTATION;
            case PHASE_7_QA_VERIFICATION -> PHASE_7_WAITING_HUMAN_APPROVAL;
            case PHASE_7_WAITING_HUMAN_APPROVAL -> PHASE_8_READY_FOR_PRODUCTION_GATE;
            case PHASE_8_READY_FOR_PRODUCTION_GATE -> PHASE_9_RELEASED;
            case PHASE_9_RELEASED, FAILED -> this;
        };
    }
}
